import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { chromium } from 'playwright';
const config=Object.fromEntries(readFileSync('.env.docling.local','utf8').trim().split('\n').map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}));
if(config.NEXT_PUBLIC_SUPABASE_URL!=='http://127.0.0.1:58321') throw Error('Isolated local test only');
const admin=createClient(config.NEXT_PUBLIC_SUPABASE_URL,config.SUPABASE_SECRET_KEY,{auth:{persistSession:false}});
const email='docling-test-'+Date.now()+'@rpaper.test';const password=randomBytes(24).toString('base64url');
const {data,error}=await admin.auth.admin.createUser({email,password,email_confirm:true});if(error)throw error;
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const started=Date.now();
try {
await page.goto('http://localhost:3001/auth/sign-in');
await page.getByLabel('Email address').fill(email);
await page.getByRole('textbox',{name:'Password Show password'}).fill(password);
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.waitForURL('**/library');
writeFileSync('tmp/docling-local/browser-session.json',JSON.stringify(await page.context().storageState()),{mode:0o600});
await page.getByRole('button',{name:'Add a research paper',exact:true}).first().click();
await page.locator('input[type=file]').setInputFiles(process.argv[2] || 'docling-lab/inputs/camera-ready.pdf');
await page.getByRole('button',{name:'Upload and parse',exact:true}).click();
await page.waitForURL('**/processing',{timeout:60000});console.log('Uploaded through the actual app. Waiting for local inference.');
await page.getByRole('link',{name:'Read paper',exact:true}).waitFor({timeout:900000});
await page.getByRole('link',{name:'Read paper',exact:true}).click();
await page.waitForURL('**/read');
await page.locator('.paper-content img').first().waitFor();
await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('.paper-content img')].map(i=>i.decode().catch(()=>{})))});
const result=await page.evaluate(()=>({blocks:document.querySelectorAll('[data-source-id]').length,headings:document.querySelectorAll('nav[aria-label="Document contents"] a').length,images:document.querySelectorAll('.paper-content img').length,broken:[...document.querySelectorAll('.paper-content img')].filter(i=>!i.naturalWidth).length,subscripts:document.querySelectorAll('.paper-content sub').length,tableCells:document.querySelectorAll('.paper-content td').length}));
if(result.blocks!==137||result.headings!==19||result.broken||errors.length)throw Error(JSON.stringify({result,errors}));
const heading=await page.locator('.paper-content h2').filter({hasText:'LIMITATIONS'}).innerText();
if(heading.split('LIMITATIONS').length!==2)throw Error('Duplicated OCR heading in reader');
await page.screenshot({path:'tmp/docling-local/reader.png',fullPage:false});
const {data:docs}=await admin.from('documents').select('id,active_version_id,status').eq('owner_id',data.user.id);
const {data:version}=await admin.from('document_versions').select('parser_version,block_count,page_count').eq('id',docs[0].active_version_id).single();
const seconds=Math.round((Date.now()-started)/1000);
console.log(JSON.stringify({reader:result,version,errors,url:page.url(),seconds},null,2));
writeFileSync('tmp/docling-local/browser-session.json',JSON.stringify(await page.context().storageState()));
writeFileSync(process.argv[2] ? 'tmp/docling-local/scan-upload-final.json' : 'tmp/docling-local/upload-verification.json',JSON.stringify({reader:result,version,errors,url:page.url(),seconds,ownerId:data.user.id},null,2));
} finally {await browser.close()}
